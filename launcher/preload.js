const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('nizay', {
  load: () => ipcRenderer.invoke('state:load'),
  save: (s) => ipcRenderer.invoke('state:save', s),
  addOffline: (n) => ipcRenderer.invoke('acc:addOffline', n),
  removeAccount: (n) => ipcRenderer.invoke('acc:remove', n),
  selectAccount: (n) => ipcRenderer.invoke('acc:select', n),
  frServer: (u) => ipcRenderer.invoke('fr:server', u),
  frState: () => ipcRenderer.invoke('fr:state'),
  frAdd: (t) => ipcRenderer.invoke('fr:add', t),
  frRemove: (t) => ipcRenderer.invoke('fr:remove', t),
  frInvite: (t) => ipcRenderer.invoke('fr:invite', t),
  frAccept: (t) => ipcRenderer.invoke('fr:accept', t),
  frLeave: () => ipcRenderer.invoke('fr:leave'),
  authMe: () => ipcRenderer.invoke('auth:me'),
  authRegister: (d) => ipcRenderer.invoke('auth:register', d),
  authLogin: (d) => ipcRenderer.invoke('auth:login', d),
  authLogout: () => ipcRenderer.invoke('auth:logout'),
  config: () => ipcRenderer.invoke('cfg:get'),
  authChangePassword: (d) => ipcRenderer.invoke('auth:changePassword', d),
  authResetPassword: (d) => ipcRenderer.invoke('auth:resetPassword', d),
  adminResetCode: (u) => ipcRenderer.invoke('admin:resetCode', u),
  adminUsers: () => ipcRenderer.invoke('admin:users'),
  subGet: () => ipcRenderer.invoke('sub:get'),
  subActivate: (k) => ipcRenderer.invoke('sub:activate', k),
  adminCreateKey: (d) => ipcRenderer.invoke('admin:createKey', d),
  adminKeys: () => ipcRenderer.invoke('admin:keys'),
  launch: () => ipcRenderer.invoke('game:launch'),
  openFolder: () => ipcRenderer.invoke('game:folder'),
  openLink: (url) => ipcRenderer.invoke('link:open', url),
  minimize: () => ipcRenderer.send('win:min'),
  close: () => ipcRenderer.send('win:close'),
  onLog: (cb) => ipcRenderer.on('game:log', (_, m) => cb(m)),
  onProgress: (cb) => ipcRenderer.on('game:progress', (_, p) => cb(p)),
  onStatus: (cb) => ipcRenderer.on('game:status', (_, m) => cb(m)),
  onError: (cb) => ipcRenderer.on('game:error', (_, m) => cb(m)),
  onState: (cb) => ipcRenderer.on('game:state', (_, s) => cb(s)),
});
